import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
// Close codes are deliberately exercised without trace/failure screenshots.
// Explicit evidence screenshots are taken only after the code is hidden.
test.use({ trace: 'off', screenshot: 'off' });
const api = 'http://127.0.0.1:3002/api/v1', adminOrigin = 'http://127.0.0.1:4178';
const email = `synthetic-live-finance-${randomUUID()}@example.test`, password = 'Synthetic live finance password';
const backend = fileURLToPath(new URL('../../backend', import.meta.url));
test.beforeAll(() => { execFileSync(process.execPath, ['--import', 'tsx', 'src/cli/create-admin.ts', '--email', email, '--name', 'Synthetic Finance Admin'], { cwd: backend, env: { ...process.env, ADMIN_BOOTSTRAP_PASSWORD: password }, stdio: 'pipe' }); });
function fixture(command: string, extra: Record<string, string>) { return JSON.parse(execFileSync(process.execPath, ['--import', 'tsx', 'tests/support/live-finance-fixtures.ts', command], { cwd: backend, env: { ...process.env, NODE_ENV: 'test', ...extra }, encoding: 'utf8' })); }
async function adminLogin(page: Page, loginEmail = email) { await page.goto(`${adminOrigin}/login`); await page.getByLabel('Email address').fill(loginEmail); await page.getByLabel('Password', { exact: true }).fill(password); await page.getByRole('button', { name: 'Sign in', exact: true }).click(); await expect(page.getByRole('heading', { name: 'Operations overview' })).toBeVisible(); }
async function action(page: Page, label: string, path: string) { await page.getByRole('button', { name: label, exact: true }).click(); const response = page.waitForResponse(value => value.url().endsWith(path) && value.request().method() === 'POST'); await page.getByRole('dialog').getByRole('button', { name: 'Confirm action', exact: true }).click(); expect((await response).status()).toBe(200); await expect(page.getByRole('dialog')).toBeHidden(); }
test('live assignment, expenses, partner code, exactly-one closure, report and published monthly statement', async ({ page, browser }, info) => {
    test.setTimeout(90000);
    const login = await page.request.post(`${api}/auth-sessions/login`, { data: { email, password } });
    expect(login.status()).toBe(200);
    const admin = await login.json();
    const headers = { Authorization: `Bearer ${admin.accessToken}`, 'Idempotency-Key': randomUUID() };
    const companyResponse = await page.request.post(`${api}/companies`, { headers, data: { legalName: 'Synthetic Finance Company', displayName: `Finance ${randomUUID().slice(0, 8)}`, contactName: 'Synthetic Contact', contactEmail: 'synthetic-finance@example.test', contactPhone: '123456789', billingAddress: 'Synthetic billing', initialPayoutRate: { driverPercent: '30.00', companyPercent: '70.00' } } });
    expect(companyResponse.status()).toBe(201);
    const company = await companyResponse.json();
    const actors = fixture('actors', { FIXTURE_ADMIN_ID: admin.user.id, FIXTURE_PASSWORD: password });
    const partnerEmail = `synthetic-finance-partner-${randomUUID()}@example.test`, initial = 'Synthetic initial finance password';
    const provision = await page.request.post(`${api}/companies/${company.id}/partners`, { headers: { ...headers, 'Idempotency-Key': randomUUID() }, data: { email: partnerEmail, fullName: 'Synthetic Finance Partner', initialPassword: initial, isPrimaryContact: true } });
    expect(provision.status()).toBe(201);
    const restricted = await (await page.request.post(`${api}/auth-sessions/login`, { data: { email: partnerEmail, password: initial } })).json();
    expect((await page.request.post(`${api}/users/me/password`, { headers: { Authorization: `Bearer ${restricted.accessToken}` }, data: { currentPassword: initial, newPassword: password } })).status()).toBe(204);
    await page.goto('/login');
    await page.getByLabel('Work email').fill(partnerEmail);
    await page.getByLabel('Password', { exact: true }).fill(password);
    const signedIn = page.waitForResponse(value => value.url().endsWith('/auth-sessions/login') && value.status() === 200);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    const partner = await (await signedIn).json();
    await expect(page.getByRole('heading', { name: 'Hello, Synthetic.' })).toBeVisible();
    await page.goto('/orders/new');
    await page.getByLabel('Pickup address').fill('Synthetic Finance Pickup');
    await page.getByLabel('Destination address').fill('Synthetic Finance Destination');
    await page.getByLabel('Pickup date · IST').fill('2026-11-01');
    await page.getByLabel('Pickup time · IST').fill('10:30');
    await page.getByLabel('Contact phone').fill('123456789');
    await page.getByRole('button', { name: 'Review request' }).click();
    const creation = page.waitForResponse(value => value.url().endsWith('/api/v1/orders') && value.request().method() === 'POST');
    await page.getByRole('button', { name: 'Submit request' }).click();
    const order = await (await creation).json();
    const adminContext = await browser.newContext({ viewport: info.project.use.viewport, isMobile: info.project.use.isMobile, hasTouch: info.project.use.hasTouch });
    const reviewerContext = await browser.newContext({ viewport: info.project.use.viewport, isMobile: info.project.use.isMobile, hasTouch: info.project.use.hasTouch });
    try {
        const operator = await adminContext.newPage();
        await adminLogin(operator);
        await operator.goto(`${adminOrigin}/orders/${order.id}`);
        await operator.getByRole('button', { name: 'Accept order', exact: true }).click();
        await operator.getByLabel('Trip amount · INR *').fill('100.01');
        const acceptance = operator.waitForResponse(value => value.url().endsWith(`/orders/${order.id}/accept`));
        await operator.getByRole('button', { name: 'Confirm acceptance' }).click();
        const accepted = await acceptance;
        expect(accepted.status()).toBe(200);
        const trip = (await accepted.json()).trip;
        await operator.getByRole('link', { name: 'View resulting trip' }).click();
        await operator.getByLabel('Active driver').selectOption(actors.driverId);
        await operator.getByLabel('Assignment reason').fill('Synthetic live dispatch');
        const assignment = operator.waitForResponse(value => value.url().endsWith(`/trips/${trip.id}/assignments`) && value.request().method() === 'POST');
        await operator.getByRole('button', { name: 'Confirm driver assignment' }).click();
        expect((await assignment).status()).toBe(201);
        await expect(operator.getByText('Driver assignment saved.', { exact: true })).toBeVisible();
        await page.goto(`/trips/${trip.id}`);
        await expect(page.getByText('Synthetic Live Driver', { exact: true })).toBeVisible();
        await expect(page.locator('.status-assigned')).toHaveText('Assigned');
        const driverLogin = await page.request.post(`${api}/auth-sessions/login`, { data: { email: actors.driverEmail, password } });
        expect(driverLogin.status()).toBe(200);
        const driver = await driverLogin.json();
        const driverHeaders = { Authorization: `Bearer ${driver.accessToken}` };
        const version = async () => { const response = await page.request.get(`${api}/trips/${trip.id}`, { headers: driverHeaders }); expect(response.status()).toBe(200); return response.headers().etag!; };
        const start = await page.request.post(`${api}/trips/${trip.id}/start`, { headers: { ...driverHeaders, 'Idempotency-Key': randomUUID(), 'If-Match': await version() }, data: {} });
        expect(start.status()).toBe(200);
        const expense = await page.request.post(`${api}/trips/${trip.id}/expenses`, { headers: { ...driverHeaders, 'Idempotency-Key': randomUUID(), 'If-Match': await version() }, data: { amount: '1.23', description: 'Synthetic live parking', category: 'parking' } });
        expect(expense.status()).toBe(201);
        await page.getByRole('button', { name: 'Refresh trip', exact: true }).click();
        await expect(page.locator('.status-ongoing')).toHaveText('Ongoing');
        await page.getByRole('button', { name: 'Refresh expenses' }).click();
        await expect(page.getByText('Synthetic live parking', { exact: true })).toBeVisible();
        const confirmation = await page.request.post(`${api}/trips/${trip.id}/expense-confirmation`, { headers: { ...driverHeaders, 'If-Match': await version() }, data: { hasNoExpenses: false } });
        expect(confirmation.status()).toBe(200);
        await page.getByRole('button', { name: 'Reveal close code' }).click();
        const revealed = page.getByLabel('Revealed close code');
        await expect(revealed).toHaveText(/^[0-9]{6}$/);
        const closeCode = (await revealed.textContent())!.trim();
        await page.getByRole('button', { name: 'Hide code' }).click();
        await expect(page.getByLabel('Close code hidden')).toBeVisible();
        const closeHeaders = { ...driverHeaders, 'Idempotency-Key': randomUUID(), 'If-Match': await version() };
        const closeBody = { code: closeCode };
        const closed = await page.request.post(`${api}/trips/${trip.id}/close`, { headers: closeHeaders, data: closeBody });
        expect(closed.status()).toBe(200);
        const closure = await closed.json();
        const retry = await page.request.post(`${api}/trips/${trip.id}/close`, { headers: closeHeaders, data: closeBody });
        expect(retry.status()).toBe(200);
        expect(await retry.json()).toEqual(closure);
        const wallet = await page.request.get(`${api}/drivers/me/wallet`, { headers: driverHeaders });
        expect((await wallet.json()).balance).toBe('30.00');
        await page.getByRole('button', { name: 'Refresh trip', exact: true }).click();
        await expect(page.getByRole('heading', { name: 'Journey completed.' })).toBeVisible();
        await expect(page.getByRole('button', { name: 'Reveal close code' })).toHaveCount(0);
        await page.goto(`/reports/${closure.reportId}`);
        await expect(page.getByRole('heading', { name: 'Recorded trip financials' })).toBeVisible();
        await expect(page.locator('.financial-summary strong')).toHaveText(['₹100.01', '₹30.00', '₹70.01']);
        await expect(page.getByText('Synthetic live parking', { exact: true })).toBeVisible();
        await page.screenshot({ path: info.outputPath('live-closed-report.png'), fullPage: true });
        const historical = fixture('history', { FIXTURE_CLOSED_TRIP_ID: trip.id });
        await operator.goto(`${adminOrigin}/statements`);
        await operator.getByLabel('Statement company').selectOption(company.id);
        await operator.getByLabel('Billing month · IST').fill(historical.billingMonth);
        const generated = operator.waitForResponse(value => value.url().endsWith('/api/v1/statements') && value.request().method() === 'POST');
        await operator.getByRole('button', { name: 'Generate draft statement' }).click();
        const draft = await generated;
        expect(draft.status()).toBe(201);
        const statement = await draft.json();
        await expect(operator.getByRole('heading', { name: 'Statement details' })).toBeVisible();
        await action(operator, 'Submit for approval', `/statements/${statement.id}/submit`);
        await action(operator, 'Approve this version', `/statements/${statement.id}/approvals`);
        const beforePublish = await page.request.get(`${api}/statements/${statement.id}`, { headers: { Authorization: `Bearer ${partner.accessToken}` } });
        expect(beforePublish.status()).toBe(404);
        const reviewer = await reviewerContext.newPage();
        await adminLogin(reviewer, actors.secondAdminEmail);
        await reviewer.goto(`${adminOrigin}/statements/${statement.id}`);
        await action(reviewer, 'Approve this version', `/statements/${statement.id}/approvals`);
        await operator.getByRole('button', { name: 'Refresh statement' }).click();
        await expect(operator.getByRole('button', { name: 'Publish statement', exact: true })).toBeEnabled();
        await action(operator, 'Publish statement', `/statements/${statement.id}/publish`);
        await expect(operator.getByText('Published to the company. Email delivery is handled separately.')).toBeVisible();
        await page.goto(`/statements/${statement.id}`);
        await expect(page.getByRole('region', { name: 'Statement trip amounts' })).toBeVisible();
        await expect(page.locator('.financial-summary strong')).toHaveText(['₹100.01', '₹30.00', '₹70.01']);
        await page.reload();
        await expect(page.getByRole('region', { name: 'Statement trip amounts' })).toBeVisible();
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
        expect(await operator.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
        await page.screenshot({ path: info.outputPath('live-published-statement.png'), fullPage: true });
        await operator.getByRole('heading', { name: 'Statement details' }).click();
        await operator.screenshot({ path: info.outputPath('live-admin-published-statement.png'), fullPage: true });
    }
    finally {
        await adminContext.close();
        await reviewerContext.close();
    }
});
